"""Adapt the pinned MIT-licensed AlperenGarip layouts without clipping cells."""
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference/match3-levels/alperen-garip'
OUTPUT = ROOT / 'public/assets/levels/imported'
OUTPUT.mkdir(parents=True, exist_ok=True)
COLORS = {'r': 1, 'g': 2, 'b': 3, 'y': 5}
SPECIALS = {'hro': 'stripe', 'vro': 'stripe', 'tnt': 'bomb', 'lb': 'color_bomb'}


def convert(source):
    width, height = source['grid_width'], source['grid_height']
    if not (1 <= width <= 10 and 1 <= height <= 10):
        raise ValueError('Unsupported source dimensions')
    if len(source['grid']) != width * height:
        raise ValueError('Source cells do not match dimensions')
    size = max(9, width, height)
    left, top = (size - width) // 2, (size - height) // 2
    grid = [[None] * size for _ in range(size)]
    blockers = [[0] * size for _ in range(size)]
    health = [[0] * size for _ in range(size)]
    powerups = []
    for index, code in enumerate(source['grid']):
        row, col = top + index // width, left + index % width
        if code not in {'rand', 'bo', 's', 'v', *COLORS, *SPECIALS}:
            raise ValueError(f'Unknown cell code: {code}')
        grid[row][col] = COLORS.get(code, 0)
        if code in {'bo', 's', 'v'}:
            blockers[row][col] = 2
            health[row][col] = 2 if code == 'v' else 1
        if code in SPECIALS:
            powerups.append({'row': row, 'col': col, 'type': SPECIALS[code], 'sourceType': code})
    count = sum(code in {'bo', 's', 'v'} for code in source['grid'])
    if not count:
        raise ValueError('Expected an obstacle-clear goal')
    return {
        'gridSize': size, 'maxMoves': source['move_count'],
        'objectives': [{'target': 'blocker', 'type': 'stone', 'count': count}],
        'gridLayout': grid, 'blockerLayout': blockers, 'stoneHealthLayout': health,
        'availableGems': ['red', 'green', 'blue', 'yellow'], 'initialPowerups': powerups,
        'source': {'repository': 'https://github.com/AlperenGarip/Match3',
                   'commit': 'd83c68675796f75749c5867d2d0cf24a2d460e1a',
                   'level': source['level_number'], 'width': width, 'height': height,
                   'left': left, 'top': top, 'license': 'MIT'},
    }


def main():
    metadata = []
    for file in sorted((SOURCE / 'original').glob('level_*.json')):
        source = json.loads(file.read_text(encoding='utf-8-sig'))
        level = convert(source)
        number = source['level_number']
        (OUTPUT / f'level_{number}.json').write_text(json.dumps(level, indent=2) + '\n', encoding='utf-8')
        metadata.append({'importedLevel': number, 'moves': level['maxMoves'], 'objectives': level['objectives']})
    assert len(metadata) == 20
    shutil.copyfile(SOURCE / 'LICENSE', OUTPUT / 'LICENSE')
    (ROOT / 'src/beauty/ImportedPhotoLevels.js').write_text(
        '// Generated by scripts/import-match3-levels.py; see assets/levels/imported/LICENSE.\n'
        + 'export const IMPORTED_PHOTO_LEVELS = ' + json.dumps(metadata, indent=4) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
